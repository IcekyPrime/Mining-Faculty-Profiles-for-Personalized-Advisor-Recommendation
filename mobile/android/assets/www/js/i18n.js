let currentLang = localStorage.getItem("lang") || "zh";

function t(key, vars) {
  const dict = I18N[currentLang] || I18N.zh;
  let s = dict[key] != null ? dict[key] : (I18N.zh[key] != null ? I18N.zh[key] : key);
  if (vars) {
    Object.keys(vars).forEach(k => { s = s.replace("{" + k + "}", vars[k]); });
  }
  return s;
}

function collegeName(name) {
  if (!name) return "";
  const key = "college." + name;
  return t(key) === key ? name : t(key);
}

function setLang(lang) {
  currentLang = lang === "en" ? "en" : "zh";
  localStorage.setItem("lang", currentLang);
  applyI18n();
}

function applyI18n() {
  document.documentElement.lang = currentLang === "en" ? "en" : "zh-CN";
  document.title = t("brand.name");
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-lang-choice]").forEach(el => {
    el.classList.toggle("active", el.dataset.langChoice === currentLang);
  });
}
